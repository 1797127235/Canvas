// 节点上是否还挂着一个服务端视频任务号（不管当前状态）。手动「查询任务」用它。
export function hasVideoTaskId(node: CanvasNodeData) {
    return node.type === CanvasNodeType.Video && Boolean(node.metadata?.videoTaskId) && !node.metadata?.content;
}

// 刷新后能自动恢复的任务：必须是 loading。
// 失败节点若残留任务号（例如建任务被上游拒绝），不能当可恢复任务去轮询，
// 否则会拿着一个数据库里不存在的任务号无限轮询（节点上还显示“任务 ID”）。
export function hasResumableVideoTask(node: CanvasNodeData) {
    return node.metadata?.status === "loading" && hasVideoTaskId(node);
}

// 账号模式图片任务在服务端执行，刷新后凭任务号恢复，不当作中断。
export function hasResumableImageTask(node: CanvasNodeData) {
    return Boolean(node.metadata?.generationTaskId || node.metadata?.images?.some((image) => image.status === "loading" && image.taskId));
}

export function resetInterruptedGeneration(nodes: CanvasNodeData[], connections: CanvasConnection[] = []) {
    // 配置节点自己不持有任务号，下游仍有可恢复的生成节点时不算中断。
    const resumableIds = new Set(nodes.filter((node) => hasResumableVideoTask(node) || hasResumableImageTask(node)).map((node) => node.id));
    const isResumable = (node: CanvasNodeData) =>
        resumableIds.has(node.id) || (node.type === CanvasNodeType.Config && connections.some((connection) => connection.fromNodeId === node.id && resumableIds.has(connection.toNodeId)));
    return nodes.map((node) => {
        if (node.metadata?.status !== "loading" || isResumable(node)) return node;
        const errorDetails = i18n.t("canvas.generation.interrupted");
        return {
            ...node,
            metadata: {
                ...node.metadata,
                status: "error" as const,
                errorDetails,
                images: node.metadata.images?.map((image) => (image.status === "loading" && !image.taskId ? { ...image, status: "error" as const, errorDetails } : image)),
                texts: node.metadata.texts?.map((text) => (text.status === "loading" ? { ...text, status: "error" as const, errorDetails } : text)),
            },
        };
    });
}

export function isGenerationCanceled(error: unknown) {
    return error instanceof Error && (error.message === i18n.t("common.requestCanceled") || error.name === "AbortError");
}

export function findRetrySourceNode(nodeId: string, nodes: CanvasNodeData[], connections: CanvasConnection[]) {
    const queue = connections.filter((connection) => connection.toNodeId === nodeId).map((connection) => connection.fromNodeId);
    const visited = new Set<string>();
    while (queue.length) {
        const id = queue.shift()!;
        if (visited.has(id)) continue;
        visited.add(id);
        const node = nodes.find((item) => item.id === id);
        if (node?.type === CanvasNodeType.Config) return node;
        connections.filter((connection) => connection.toNodeId === id).forEach((connection) => queue.push(connection.fromNodeId));
    }
    return null;
}

export function sourceNodeReferenceImages(node: CanvasNodeData | null) {
    if (!node || node.type !== CanvasNodeType.Image || !node.metadata?.content) return [];
    return [
        {
            id: node.id,
            name: `${node.title || node.id}.png`,
            type: node.metadata.mimeType || "image/png",
            dataUrl: node.metadata.content,
            storageKey: node.metadata.storageKey,
        },
    ];
}

export function isAudioFile(file: File) {
    return file.type.startsWith("audio/") || /\.(mp3|wav)$/i.test(file.name);
}

export function buildAngleLabel(params: CanvasImageAngleParams) {
    const horizontal = params.horizontalAngle === 0 ? i18n.t("canvas.generation.front") : params.horizontalAngle > 0 ? i18n.t("canvas.generation.rotateRight", { angle: params.horizontalAngle }) : i18n.t("canvas.generation.rotateLeft", { angle: Math.abs(params.horizontalAngle) });
    const pitch = params.pitchAngle === 0 ? i18n.t("canvas.generation.level") : params.pitchAngle > 0 ? i18n.t("canvas.generation.topDown", { angle: params.pitchAngle }) : i18n.t("canvas.generation.lowAngle", { angle: Math.abs(params.pitchAngle) });
    return i18n.t("canvas.generation.angleLabel", { horizontal, pitch, distance: params.cameraDistance.toFixed(1), lens: i18n.t(params.wideAngle ? "canvas.editors.wide" : "canvas.editors.standard") });
}

export function buildAnglePrompt(params: CanvasImageAngleParams) {
    return i18n.t("canvas.generation.anglePrompt", { angle: buildAngleLabel(params) });
}
